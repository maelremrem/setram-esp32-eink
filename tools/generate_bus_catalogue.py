#!/usr/bin/env python3
"""Regenerate offline portal: python tools/generate_bus_catalogue.py [--zip official.zip]."""
import argparse
import datetime
import gzip
import hashlib
import json
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from setram import STATIC_URL, download, parse_gtfs
ROOT = Path(__file__).resolve().parents[1]

def safe_label(text):
    text = ''.join(' ' if ord(c) < 32 or ord(c) == 127 or c in '<>&"\'' else c for c in text)
    return text.encode('utf-8')[:64].decode('utf-8', errors='ignore')

def build_catalogue(tables):
    routes = {r['route_id']: r for r in tables['routes']}
    trips = {t['trip_id']: t for t in tables['trips']}
    patterns = {}
    for row in tables['stop_times']:
        trip = trips[row['trip_id']]
        if trip.get('direction_id') not in ('0','1'): continue
        route = routes[trip['route_id']]
        patterns.setdefault(row['stop_id'], set()).add((trip['route_id'], route.get('route_short_name') or route.get('route_long_name',''), trip['direction_id'], trip.get('trip_headsign','')))
    stops = []
    for stop in tables['stops']:
        if stop.get('location_type','') not in ('','0') or stop['stop_id'] not in patterns: continue
        stops.append({'id':stop['stop_id'], 'name':stop['stop_name'], 'services':[dict(zip(('route','line','direction','destination'), p)) for p in sorted(patterns[stop['stop_id']])]})
    return {'stops':sorted(stops, key=lambda s:(s['name'],s['id']))}

def cpp(text): return json.dumps(text, ensure_ascii=False)

def main():
    parser = argparse.ArgumentParser(description=__doc__); parser.add_argument('--zip', type=Path)
    args = parser.parse_args()
    if args.zip:
        raw = args.zip.read_bytes(); final_url = STATIC_URL
    else:
        raw, status, final_url = download(STATIC_URL, 60)
        if status != 200: raise ValueError('GTFS HTTP status not 200')
    data = build_catalogue(parse_gtfs(raw))
    data['source'] = {'url':STATIC_URL, 'final_url':final_url, 'sha256':hashlib.sha256(raw).hexdigest(), 'generated_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(), 'resource':'transport.data.gouv.fr resource 84170', 'warning':'Catalogue statique embarqué : peut être périmé. Il ne garantit pas les passages en temps réel.', 'regenerate':'python tools/generate_bus_catalogue.py'}
    out = ROOT / 'lib/BusCatalog'; out.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, separators=(',',':')).encode()
    (out/'catalogue.json').write_bytes(payload)
    zipped = gzip.compress(payload, mtime=0); (out/'catalogue.json.gz').write_bytes(zipped)
    lines = ['// Generated by tools/generate_bus_catalogue.py. Do not edit.', '#pragma once', 'namespace busCatalog {', 'static const Entry entries[] = {']
    count = 0
    for stop in data['stops']:
        for service in stop['services']:
            values = [stop['id'], service['route'], service['direction'], safe_label(stop['name']), safe_label(service['line']), safe_label(service['destination'])]
            lines.append('{' + ','.join(cpp(v) for v in values) + '},'); count += 1
    lines += ['};', 'static const unsigned char catalogueGzip[] = {', ','.join(str(b) for b in zipped), '};', '}']
    (out/'GeneratedCatalogue.h').write_text('\n'.join(lines)+'\n')
    web = ROOT / 'lib/BusPortal'
    if (web/'portal.html').exists():
        (web/'GeneratedPortal.h').write_text('#pragma once\nstatic const char portalHtml[] PROGMEM = R"BUSPORTAL(' + (web/'portal.html').read_text() + ')BUSPORTAL";\n')
    print(json.dumps({'stops':len(data['stops']), 'patterns':count, 'json_bytes':len(payload), 'gzip_bytes':len(zipped), 'source':data['source']}, ensure_ascii=False, indent=2))
if __name__ == '__main__': main()
